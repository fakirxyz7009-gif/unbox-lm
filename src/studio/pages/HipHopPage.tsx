/**
 * Hip-Hop Kits: tap through every pad of the eight synthesised hip-hop banks (1,000 one-shots).
 * Pads play on a transient device into the monitor, so auditioning never adds a rack unit, cable or
 * undo step. Click a pad, step through the kit from the keyboard with the arrow keys (→ / ↓ hit the
 * highlighted pad and move on, ← / ↑ step back), or start WALK to loop the whole kit hands-free at
 * the project tempo or a fixed, slower pace. The kit, pace and last pad live in the project
 * (src/audio/hiphopAudition.ts), so a saved project reopens on the same spot on any machine. The
 * sounds themselves are generated by scripts/instruments/hiphop.
 */
import React, { useEffect, useRef, useState } from 'react';
import { audioEngine } from '../../audio/AudioEngine.ts';
import { hiphopAudition } from '../../audio/hiphopAudition.ts';
import { KitAudition } from '../../audio/kitAudition.ts';
import type { DeviceType } from '../../audio/types.ts';
import { DEVICE_SPECS, SPEC_BY_TYPE } from '../../../shared/rack/devices/index.ts';
import { Btn, Panel, Sel } from '../ui/controls.tsx';

/** The eight banks, in bank order, from the generated device catalog. */
const KITS = DEVICE_SPECS.filter((spec) => spec.type.startsWith('rec_hiphop')).map((spec) => ({
  type: spec.type as DeviceType,
  name: spec.name,
  pads: spec.pads?.length ?? 0,
}));
const TOTAL_PADS = KITS.reduce((total, kit) => total + kit.pads, 0);

type Status = 'loading' | 'ready' | 'error';
/** Walk step: a note value of the project tempo, or a fixed pace in seconds for close listening. */
type Pace = '1/4' | '1/8' | '1/16' | '0.75' | '1' | '1.5' | '2';
const PACES: { value: Pace; label: string }[] = [
  { value: '1/4', label: '1/4 · tempo' },
  { value: '1/8', label: '1/8 · tempo' },
  { value: '1/16', label: '1/16 · tempo' },
  { value: '0.75', label: '0.75 s' },
  { value: '1', label: '1 s' },
  { value: '1.5', label: '1.5 s' },
  { value: '2', label: '2 s' },
];
const isTempoLocked = (pace: Pace): boolean => pace === '1/4' || pace === '1/8' || pace === '1/16';

/** Seconds per walk step: a note value of the project tempo, or the chosen fixed pace. */
function stepSeconds(pace: Pace): number {
  if (!isTempoLocked(pace)) return Number(pace);
  const bpm = Math.max(20, Math.min(300, audioEngine.bpm));
  const beats = pace === '1/4' ? 1 : pace === '1/8' ? 0.5 : 0.25;
  return (60 / bpm) * beats;
}

/** Opens on the project's kit / pace / pad, falling back when the saved values are unknown. */
function restoredSettings(): { kit: DeviceType; pace: Pace; cursor: number } {
  const stored = hiphopAudition.get();
  const kit = KITS.some((entry) => entry.type === stored.kit) ? (stored.kit as DeviceType) : (KITS[0]?.type ?? 'rec_hiphop_kicks');
  const pace = PACES.some((entry) => entry.value === stored.pace) ? (stored.pace as Pace) : '1/8';
  const lanes = SPEC_BY_TYPE.get(kit)?.pads ?? [];
  const index = lanes.findIndex((lane) => lane.note === stored.pad);
  return { kit, pace, cursor: index < 0 ? 0 : index };
}

export function HipHopPage() {
  const [initial] = useState(restoredSettings);
  const [kit, setKit] = useState<DeviceType>(initial.kit);
  const [status, setStatus] = useState<Status>('loading');
  const [lastPad, setLastPad] = useState<{ name: string; note: number } | null>(null);
  /** Pad the arrow keys hit next; kept in step with the last click and the walk. */
  const [cursor, setCursor] = useState(initial.cursor);
  const [walking, setWalking] = useState(false);
  const [pace, setPace] = useState<Pace>(initial.pace);
  const audition = useRef<KitAudition | null>(null);
  const padRefs = useRef<Array<HTMLButtonElement | null>>([]);
  const walkIndex = useRef(0);
  /** First kit load keeps the restored cursor; a later kit change starts at pad 1. */
  const firstLoad = useRef(true);
  /** Pad index a project load wants, applied when its kit has loaded. */
  const pendingPad = useRef<number | null>(null);

  useEffect(() => {
    const player = audition.current ?? (audition.current = new KitAudition());
    let cancelled = false;
    setStatus('loading');
    setLastPad(null);
    setWalking(false);
    if (firstLoad.current) {
      firstLoad.current = false;
    } else {
      const pending = pendingPad.current;
      pendingPad.current = null;
      setCursor(pending ?? 0);
    }
    player
      .load(kit)
      .then(() => {
        if (!cancelled) setStatus('ready');
      })
      .catch(() => {
        if (!cancelled) setStatus('error');
      });
    return () => {
      cancelled = true;
    };
  }, [kit]);

  useEffect(
    () => () => {
      audition.current?.dispose();
      audition.current = null;
    },
    [],
  );

  const pads = SPEC_BY_TYPE.get(kit)?.pads ?? [];
  const kitName = KITS.find((entry) => entry.type === kit)?.name ?? 'Hip-Hop Kit';
  const cursorNote = pads[cursor]?.note ?? 0;

  // The audition spot is part of the project: these writes are picked up by the project's autosave
  // and by Save, so nothing here touches browser storage.
  useEffect(() => {
    hiphopAudition.update({ kit });
  }, [kit]);
  useEffect(() => {
    hiphopAudition.update({ pace });
  }, [pace]);
  useEffect(() => {
    hiphopAudition.update({ pad: cursorNote });
  }, [cursorNote]);

  // A loaded project replaces what this page is showing.
  useEffect(
    () =>
      hiphopAudition.subscribe(() => {
        const stored = hiphopAudition.get();
        if (PACES.some((entry) => entry.value === stored.pace)) setPace(stored.pace as Pace);
        if (!KITS.some((entry) => entry.type === stored.kit)) return;
        const nextKit = stored.kit as DeviceType;
        const lanes = SPEC_BY_TYPE.get(nextKit)?.pads ?? [];
        const index = lanes.findIndex((lane) => lane.note === stored.pad);
        if (nextKit === kit) {
          if (index >= 0) setCursor(index);
        } else {
          pendingPad.current = index >= 0 ? index : null;
          setKit(nextKit);
        }
      }),
    [kit],
  );

  // Bring the reopened pad into view once the grid exists.
  useEffect(() => {
    padRefs.current[initial.cursor]?.scrollIntoView({ block: 'nearest' });
  }, [initial.cursor]);

  /** Plays one pad; `step` also moves the highlight, so a key press hits then advances. */
  const hit = (index: number, step: -1 | 0 | 1 = 0) => {
    const count = pads.length;
    if (!count) return;
    const at = ((index % count) + count) % count;
    const pad = pads[at];
    audition.current?.tap(pad.note);
    void audioEngine.resumeContext();
    setLastPad({ name: pad.name, note: pad.note });
    const next = (((at + step) % count) + count) % count;
    setCursor(next);
    padRefs.current[next]?.scrollIntoView({ block: 'nearest' });
  };

  useEffect(() => {
    const onKeyDown = (event: KeyboardEvent) => {
      if (event.altKey || event.ctrlKey || event.metaKey || event.shiftKey) return;
      const target = event.target as HTMLElement | null;
      const tag = target?.tagName;
      if (tag === 'INPUT' || tag === 'TEXTAREA' || tag === 'SELECT' || target?.isContentEditable) return;
      // Space belongs to this page while it is open: the transport is left alone (see App.tsx).
      if (event.code === 'Space') {
        if (status !== 'ready' || !pads.length) return;
        event.preventDefault();
        if (walking) {
          setWalking(false);
        } else {
          walkIndex.current = Math.min(cursor, pads.length - 1);
          void audioEngine.resumeContext();
          setWalking(true);
        }
        return;
      }
      if (event.key === 'ArrowRight' || event.key === 'ArrowDown') {
        event.preventDefault();
        hit(cursor, 1);
      } else if (event.key === 'ArrowLeft' || event.key === 'ArrowUp') {
        event.preventDefault();
        hit(cursor - 1, 0);
      }
    };
    window.addEventListener('keydown', onKeyDown);
    return () => window.removeEventListener('keydown', onKeyDown);
  }, [cursor, kit, status, walking]);

  /**
   * Walk: pads are scheduled a little ahead on the AudioContext clock, so the gaps are musical even
   * when the main thread is busy — the UI highlight simply follows what was just queued.
   */
  useEffect(() => {
    if (!walking) return;
    const step = stepSeconds(pace);
    const ctx = audioEngine.ctx;
    let index = walkIndex.current;
    let next = ctx.currentTime + 0.12;
    const timer = window.setInterval(() => {
      while (next < ctx.currentTime + 0.25 && pads.length) {
        // Loops: after the last pad the walk starts again at pad 1 until STOP is pressed.
        const at = ((index % pads.length) + pads.length) % pads.length;
        const pad = pads[at];
        audition.current?.tap(pad.note, 0.85, next);
        setLastPad({ name: pad.name, note: pad.note });
        setCursor(at);
        padRefs.current[at]?.scrollIntoView({ block: 'nearest' });
        index = at + 1;
        walkIndex.current = index;
        next += step;
      }
    }, 25);
    return () => window.clearInterval(timer);
  }, [walking, pace, kit]);

  const toggleWalk = () => {
    if (walking) {
      setWalking(false);
      return;
    }
    if (!pads.length) return;
    walkIndex.current = Math.min(cursor, pads.length - 1);
    void audioEngine.resumeContext();
    setWalking(true);
  };

  return (
    <div className="flex-1 min-h-0 overflow-auto p-3 bg-[#070a10] text-slate-200 text-[11px]" data-testid="hiphop-page">
      <div className="flex items-center gap-3 mb-3">
        <h2 className="text-[13px] font-black text-white">Hip-Hop Kits</h2>
        <span className="text-slate-500">
          {KITS.length} synthesised banks · {TOTAL_PADS} pads · CC0, generated in-repo (no recordings)
        </span>
        <div className="flex-1" />
        <span className={status === 'error' ? 'text-red-400' : status === 'loading' ? 'text-amber-300' : 'text-emerald-400'}>
          {status === 'error' ? 'Kit failed to load' : status === 'loading' ? 'Loading kit…' : 'Kit ready · tap a pad'}
        </span>
      </div>

      <div className="flex flex-wrap items-center gap-1 mb-3">
        {KITS.map((entry) => (
          <Btn key={entry.type} on={entry.type === kit} onClick={() => setKit(entry.type)} title={`${entry.name} · ${entry.pads} pads`}>
            {entry.name}
          </Btn>
        ))}
      </div>

      <div className="flex flex-wrap items-center gap-2 mb-3">
        <Btn on={walking} disabled={status !== 'ready'} onClick={toggleWalk} title="Loop the kit in tempo from the highlighted pad, one pad per step, until you stop it">
          {walking ? '■ STOP WALK' : '▶ WALK KIT'}
        </Btn>
        <span className="text-slate-500">Pace</span>
        <Sel value={pace} onChange={setPace} options={PACES} title="Walk step: a note value of the project tempo, or a fixed pace in seconds" />
        <span className="text-slate-500">
          {isTempoLocked(pace) ? `@ ${Math.round(audioEngine.bpm)} BPM` : `${stepSeconds(pace)} s per pad`} · {pads.length} steps · loops · starts at the highlighted pad
        </span>
      </div>

      <Panel
        title={`${kitName} · ${pads.length} pads`}
        right={
          <span className="text-slate-400">
            {lastPad ? (
              <>
                <span className="font-mono text-slate-500">{String(lastPad.note).padStart(3, '0')}</span> {lastPad.name}
              </>
            ) : (
              'Played on a transient device through the monitor'
            )}
          </span>
        }
      >
        <div className="grid gap-1" style={{ gridTemplateColumns: 'repeat(auto-fill, minmax(108px, 1fr))' }}>
          {pads.map((pad, index) => (
            <button
              key={pad.note}
              ref={(el) => {
                padRefs.current[index] = el;
              }}
              type="button"
              title={`${pad.name} · note ${pad.note}`}
              aria-current={index === cursor ? 'true' : undefined}
              onClick={() => hit(index)}
              className={`h-8 truncate rounded border px-2 text-left text-[11px] ${
                index === cursor
                  ? 'border-amber-400 bg-amber-400/15 text-white ring-1 ring-amber-400'
                  : 'border-slate-700 bg-slate-900 text-slate-300 hover:border-amber-500 hover:bg-slate-800 hover:text-white'
              } active:bg-amber-400 active:text-black`}
            >
              <span className="font-mono text-slate-500">{String(pad.note).padStart(3, '0')}</span> {pad.name}
            </button>
          ))}
        </div>
        <div className="mt-2 text-slate-500">
          <span className="font-mono text-slate-300">
            {String(cursor + 1).padStart(3, '0')}/{pads.length}
          </span>{' '}
          · <kbd>→</kbd> / <kbd>↓</kbd> hit the highlighted pad and step forward · <kbd>←</kbd> / <kbd>↑</kbd> step back · click a pad to jump · <kbd>Space</kbd> starts / stops the walk (transport stays untouched)
        </div>
      </Panel>
    </div>
  );
}
