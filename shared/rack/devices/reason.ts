function channelStrip(n: number, o: { eq?: boolean; aux?: boolean; solo?: boolean } = {}): ParamDef[] {
  const p: ParamDef[] = [];
  for (let i = 1; i <= n; i++) {
    const section = `Ch ${i}`;
    p.push(db(`ch${i}Level`, `Ch ${i}`, -60, 6, 0, { section, control: 'fader' }), knob(`ch${i}Pan`, 'Pan', -1, 1, 0, { section }), toggle(`ch${i}Mute`, 'M', 0, { section }));
    if (o.solo) p.push(toggle(`ch${i}Solo`, 'S', 0, { section }));
    if (o.eq) p.push(db(`ch${i}Bass`, 'Bass', -12, 12, 0, { section }), db(`ch${i}Treble`, 'Treble', -12, 12, 0, { section }));
    if (o.aux) p.push(pct(`ch${i}Aux`, 'Aux', 0, { section }));
  }
  if (o.aux) p.push(pct('auxReturn', 'Aux Return', 0.8, { section: 'Master' }));
  p.push(db('master', 'Master', -60, 6, 0, { section: 'Master', control: 'fader', cv: true }));
  return p;
}

